import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const location = path.join(root, "scaffold", "presets", "example-c99");
const manifest = JSON.parse(await fs.readFile(path.join(location, "manifest.json"), "utf8"));
const code = {};
for (const c of manifest.components) {
  const full = path.resolve(location, c.source);
  if (!full.startsWith(location + path.sep)) throw new Error("Unsafe preset path: " + c.source);
  code[c.id] = await fs.readFile(full, "utf8");
}
const generated = [
  "// Auto-generated by scripts/embed-standalone-preset.mjs; do not edit by hand.",
  'import type { LoadedPreset, PresetManifest } from "./scaffold";',
  "const manifest: PresetManifest = " + JSON.stringify(manifest, null, 2) + ";",
  "const sources: Record<string, string> = " + JSON.stringify(code, null, 2) + ";",
  "export function builtinPreset(): LoadedPreset {",
  "  const byId = new Map(manifest.components.map(c => [c.id, c]));",
  "  const visited = new Set<string>();",
  "  const order: string[] = [];",
  "  const visit = (id: string): void => {",
  "    if (visited.has(id)) return;",
  "    visited.add(id);",
  "    for (const dep of byId.get(id)!.requires) visit(dep);",
  "    order.push(id);",
  "  };",
  "  for (const c of manifest.components) visit(c.id);",
  "  return { manifest, code: new Map(Object.entries(sources)), order };",
  "}",
  ""
].join("\n");
await fs.writeFile(path.join(root, "src", "standalone", "generated-preset.ts"), generated);
console.log("Embedded the configured C99 example preset.");
